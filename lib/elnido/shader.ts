// WebGL shaders for the El Nido scene, from design/elnido-scene/index.html. The moon is drawn over the
// canvas in CSS (.scene-moon); the shader only uses its position to keep twinkling stars off it.

export const VS = 'attribute vec2 p; varying vec2 vS; void main(){ vS = vec2(p.x*0.5+0.5, 0.5-p.y*0.5); gl_Position = vec4(p,0.,1.); }';
export const FS = [
  'precision highp float;',
  'varying vec2 vS;',
  'uniform sampler2D tA, tB, tM;',
  'uniform float mixF, t, ripple, sparkle, fog, stars, lantern, drift, asp;',
  'uniform vec3 fogC, bakedA, bakedB;',
  'uniform vec2 uvS, uvO;',
  'uniform vec4 sun;',      // xy pos, radius, strength
  'uniform vec3 sunCol;',
  'uniform vec3 moon;',     // xy pos, radius
  'uniform float warmth;',
  'float h(vec2 p){ return fract(sin(dot(p, vec2(127.1,311.7)))*43758.5453); }',
  'float n(vec2 p){ vec2 i=floor(p), f=fract(p); f=f*f*(3.-2.*f);',
  '  return mix(mix(h(i),h(i+vec2(1,0)),f.x), mix(h(i+vec2(0,1)),h(i+vec2(1,1)),f.x), f.y); }',
  'float fbm(vec2 p){ float s=0., a=.5; for(int i=0;i<4;i++){ s+=a*n(p); p*=2.03; a*=.5; } return s; }',
  // smooth simplex noise for the water surface (no square cells)
  'vec3 pm(vec3 x){ return mod(((x*34.0)+1.0)*x, 289.0); }',
  'float sn(vec2 v){',
  '  const vec4 C = vec4(0.211324865405187, 0.366025403784439, -0.577350269189626, 0.024390243902439);',
  '  vec2 i = floor(v + dot(v, C.yy)); vec2 x0 = v - i + dot(i, C.xx);',
  '  vec2 i1 = (x0.x > x0.y) ? vec2(1.0, 0.0) : vec2(0.0, 1.0);',
  '  vec4 x12 = x0.xyxy + C.xxzz; x12.xy -= i1; i = mod(i, 289.0);',
  '  vec3 p = pm(pm(i.y + vec3(0.0, i1.y, 1.0)) + i.x + vec3(0.0, i1.x, 1.0));',
  '  vec3 m = max(0.5 - vec3(dot(x0,x0), dot(x12.xy,x12.xy), dot(x12.zw,x12.zw)), 0.0); m = m*m; m = m*m;',
  '  vec3 x = 2.0 * fract(p * C.www) - 1.0; vec3 h = abs(x) - 0.5; vec3 ox = floor(x + 0.5); vec3 a0 = x - ox;',
  '  m *= 1.79284291400159 - 0.85373472095314 * (a0*a0 + h*h);',
  '  vec3 g; g.x = a0.x * x0.x + h.x * x0.y; g.yz = a0.yz * x12.xz + h.yz * x12.yw;',
  '  return 130.0 * dot(m, g);',
  '}',
  // wave height: two crossing swells, wider than tall like real chop seen from above
  'float wave(vec2 uv, float persp, float t){',
  '  vec2 q = vec2(uv.x*mix(46.,13.,persp), uv.y*mix(190.,44.,persp));',
  '  return 0.6*sn(q + vec2(t*0.22, t*0.38)) + 0.4*sn(q*1.9 + vec2(-t*0.31, t*0.27));',
  '}',
  // Read a plate with its painted sun/moon filled in from the surrounding sky
  'vec3 plate(sampler2D tx, vec2 u, vec3 bk){',
  '  vec3 c = texture2D(tx, u).rgb;',
  '  if (bk.z <= 0.0) return c;',
  '  vec2 dv = (u - bk.xy) * vec2(asp, 1.0); float dd = length(dv);',
  '  float m = 1.0 - smoothstep(bk.z*1.05, bk.z*1.7, dd);',
  '  if (m <= 0.0) return c;',
  '  vec3 acc = vec3(0.0); float wsum = 0.0; vec2 dir = dv / max(dd, 1e-5);',
  '  for (int i = 0; i < 16; i++) { float a = 6.2831853*float(i)/16.0; vec2 o = vec2(cos(a), sin(a));',
  '    float w = 0.35 + max(dot(o, dir), 0.0);',
  '    acc += w * texture2D(tx, bk.xy + o*vec2(1.0/asp, 1.0)*bk.z*1.95).rgb; wsum += w; }',
  '  return mix(c, acc/wsum, m);',
  '}',
  'float lumAt(vec2 u){ return dot(mix(texture2D(tA,u).rgb, texture2D(tB,u).rgb, mixF), vec3(0.299,0.587,0.114)); }',
  'void main(){',
  '  vec2 uv = vS*uvS + uvO;',
  '  vec4 m = texture2D(tM, uv);',
  '  float water = m.r, skyM = m.g, boat = m.b, calm = m.a;',
  '  float dispW = smoothstep(0.62, 0.98, water) * (1.0 - calm) * (1.0 - boat);',
  '  float persp = mix(0.12, 1.0, smoothstep(0.40, 1.0, uv.y));',
  '  vec2 q = vec2(uv.x*mix(34.,9.,persp), uv.y*mix(150.,30.,persp));',
  '  float w0 = wave(uv, persp, t);',
  '  vec2 e = vec2(0.0015, 0.0008);',
  '  vec2 grad = vec2(wave(uv + vec2(e.x, 0.0), persp, t) - w0, wave(uv + vec2(0.0, e.y), persp, t) - w0);',
  '  vec2 d = grad * vec2(0.06, 0.044) * ripple * persp * dispW;',
  '  vec2 sq = uv*vec2(2.6,5.0) + vec2(t*0.012, 0.0);',
  '  float skyOcc = smoothstep(0.0, 0.05, skyM) * (1.0 - smoothstep(0.394, 0.40, uv.y));',
  '  vec2 sd = vec2(fbm(sq)-0.5, (fbm(sq+7.3)-0.5)*0.5) * 0.004 * smoothstep(0.35, 1.0, skyM) * drift;',
  '  float bob = (sin(t*1.5 + uv.x*23.0)*0.0011 + sin(t*0.9 + uv.x*11.0)*0.0006) * boat;',
  '  vec2 u2 = uv + d + sd + vec2(0.0, bob);',
  '  vec3 col = mix(plate(tA, u2, bakedA), plate(tB, u2, bakedB), mixF);',
  // low-sun warmth across the whole scene during morning light and golden hour
  '  col *= mix(vec3(1.0), vec3(1.07, 0.98, 0.88), warmth);',
  '  float lum = dot(col, vec3(0.299,0.587,0.114));',
  // live sky: only inside the sky, cut at the horizon line
  '  float skyCut = skyOcc;',
  '  vec2 sv = (uv - sun.xy) * vec2(asp, 1.0); float sdist = length(sv);',
  '  float sDisc = 1.0 - smoothstep(sun.z*0.9, sun.z, sdist);',
  '  float sGlow = exp(-sdist / (sun.z*3.2)) * 0.55 + exp(-sdist / (sun.z*12.0)) * 0.25;',
  '  col += sunCol * sGlow * sun.w * (0.2 + 0.8*skyOcc);',
  '  vec3 core = mix(sunCol, vec3(1.0, 0.97, 0.88), 0.5 - 0.35*smoothstep(0.0, 1.0, sdist/sun.z)) * 1.3;',
  '  col = mix(col, core, sDisc * skyCut * sun.w);',
  '  float md = length((uv - moon.xy) * vec2(asp, 1.0));',
  // sun glitter path on the water under a low sun
  '  float lowSun = step(sun.y, 0.398) * (1.0 - smoothstep(0.08, 0.30, 0.40 - sun.y));',
  '  float path = exp(-abs(uv.x - sun.x) * mix(60.0, 14.0, persp)) * water * smoothstep(0.40, 0.46, uv.y);',
  '  float glit = pow(n(uv*vec2(260.,700.) + vec2(t*1.2,-t*0.8)), 5.0);',
  '  col += sunCol * path * glit * 1.6 * sun.w * lowSun;',
  // light shimmer over the shallows
  '  col *= 1.0 + dispW*persp*0.045*sn(uv*vec2(38.,70.) + vec2(t*0.18,-t*0.11));',
  // sparkles on bright water
  // glints: light catching the steep side of a wave, small and short-lived
  '  float slope = length(grad / vec2(e.x*mix(46.,13.,persp), e.y*mix(190.,44.,persp)));',
  '  vec2 gq = vec2(uv.x*mix(260.,90.,persp), uv.y*mix(900.,260.,persp));',
  '  float flick = smoothstep(0.62, 0.95, sn(gq + vec2(t*0.9, -t*0.6)));',
  '  float glint = smoothstep(1.6, 2.4, slope) * flick;',
  '  col += vec3(1.0,0.98,0.93) * glint * 0.75 * sparkle * dispW * smoothstep(0.25, 0.7, lum) * persp * persp;',
  // drifting low mist near the horizon
  '  float band = smoothstep(0.36,0.46,uv.y) * (1.0 - smoothstep(0.50,0.66,uv.y));',
  '  float mist = band * fbm(vec2(uv.x*3.5 - t*0.025, uv.y*14.0 + t*0.01));',
  '  col = mix(col, fogC, clamp(mist*fog*0.42, 0.0, 0.5));',
  // twinkling stars, kept off the moon
  '  vec2 px = vec2(2.5/2752.0, 2.5/1536.0);',
  '  float nb = 0.25*(lumAt(u2+vec2(px.x,0.0)) + lumAt(u2-vec2(px.x,0.0)) + lumAt(u2+vec2(0.0,px.y)) + lumAt(u2-vec2(0.0,px.y)));',
  '  float starPix = smoothstep(0.05, 0.16, lumAt(u2) - nb) * skyOcc * stars * smoothstep(moon.z*1.2, moon.z*3.0, md);',
  '  vec2 cell = floor(uv*vec2(900.,500.));',
  '  float tw = sin(t*(2.0 + 3.0*h(cell)) + 6.283*h(cell+3.1));',
  '  col *= 1.0 + starPix * tw * 0.45;',
  // lantern flicker on warm pixels around the boats at night
  '  float warm = smoothstep(0.08, 0.28, col.r - col.b) * smoothstep(0.45, 0.8, col.r);',
  '  float fl = 0.88 + 0.22*n(vec2(t*7.0, floor(uv.x*60.0)));',
  '  col *= mix(1.0, fl, warm * lantern * max(water, boat));',
  '  gl_FragColor = vec4(col, 1.0);',
  '}'
].join('\n')
